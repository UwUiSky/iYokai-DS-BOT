-- 1. Politica dei comandi: l'elenco dei comandi spenti di ogni server.
UPDATE guild_config g
SET settings = jsonb_set(g.settings, '{policy_comandi_off}', (
    SELECT COALESCE(jsonb_agg(DISTINCT to_jsonb(COALESCE(m.nuovo, e.v))), '[]'::jsonb)
    FROM jsonb_array_elements_text(g.settings -> 'policy_comandi_off') AS e(v)
    LEFT JOIN _riordino_d137 m ON m.vecchio = e.v))
WHERE jsonb_typeof(g.settings -> 'policy_comandi_off') = 'array';

-- 2. Ruoli richiesti per comando o gruppo: {percorso: [id ruolo, ...]}.
UPDATE guild_config g
SET settings = jsonb_set(g.settings, '{policy_ruoli_richiesti}', (
    SELECT COALESCE(jsonb_object_agg(COALESCE(m.nuovo, e.key), e.value), '{}'::jsonb)
    FROM jsonb_each(g.settings -> 'policy_ruoli_richiesti') AS e
    LEFT JOIN _riordino_d137 m ON m.vecchio = e.key))
WHERE jsonb_typeof(g.settings -> 'policy_ruoli_richiesti') = 'object';

-- 3. Registro modifiche: valori vecchio e nuovo (testo JSON), cosi' il ripristino non riaccende nulla.
UPDATE guild_config_history h
SET old_value = CASE WHEN h.old_value ~ '^\s*\[' THEN (
        SELECT COALESCE(jsonb_agg(DISTINCT to_jsonb(COALESCE(m.nuovo, e.v))), '[]'::jsonb)::text
        FROM jsonb_array_elements_text(h.old_value::jsonb) AS e(v)
        LEFT JOIN _riordino_d137 m ON m.vecchio = e.v) ELSE h.old_value END,
    new_value = CASE WHEN h.new_value ~ '^\s*\[' THEN (
        SELECT COALESCE(jsonb_agg(DISTINCT to_jsonb(COALESCE(m.nuovo, e.v))), '[]'::jsonb)::text
        FROM jsonb_array_elements_text(h.new_value::jsonb) AS e(v)
        LEFT JOIN _riordino_d137 m ON m.vecchio = e.v) ELSE h.new_value END
WHERE h.key_name = 'policy_comandi_off';

UPDATE guild_config_history h
SET old_value = CASE WHEN h.old_value ~ '^\s*\{' THEN (
        SELECT COALESCE(jsonb_object_agg(COALESCE(m.nuovo, e.key), e.value), '{}'::jsonb)::text
        FROM jsonb_each(h.old_value::jsonb) AS e
        LEFT JOIN _riordino_d137 m ON m.vecchio = e.key) ELSE h.old_value END,
    new_value = CASE WHEN h.new_value ~ '^\s*\{' THEN (
        SELECT COALESCE(jsonb_object_agg(COALESCE(m.nuovo, e.key), e.value), '{}'::jsonb)::text
        FROM jsonb_each(h.new_value::jsonb) AS e
        LEFT JOIN _riordino_d137 m ON m.vecchio = e.key) ELSE h.new_value END
WHERE h.key_name = 'policy_ruoli_richiesti';

-- 4. Ultimo comando usato.
UPDATE command_usage c
SET command_path = m.nuovo
FROM _riordino_d137 m
WHERE c.command_path = m.vecchio;

-- 5. Conteggio dei comandi usati per server e giorno: i vecchi nomi si sommano al nuovo (chiedi + cerca-comando = help).
WITH spostati AS (
    DELETE FROM comandi_uso_server u USING _riordino_d137 m WHERE u.comando = m.vecchio
    RETURNING u.guild_id, m.nuovo AS comando, u.giorno, u.usi
)
INSERT INTO comandi_uso_server (guild_id, comando, giorno, usi)
SELECT guild_id, comando, giorno, SUM(usi) FROM spostati GROUP BY guild_id, comando, giorno
ON CONFLICT (guild_id, giorno, comando) DO UPDATE SET usi = comandi_uso_server.usi + EXCLUDED.usi;

