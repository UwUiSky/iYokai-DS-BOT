    # ================================================================
    async def _handle_possible_appeal(self, message: discord.Message) -> None:
        user = message.author

        # SEC-12: al massimo un DM elaborato ogni 30 secondi per
        # utente — senza questo, chiunque può inondare il bot di DM e
        # fargli ripetere la query sui casi attivi (e il resto del
        # flusso) ad ogni singolo messaggio.
        # BUG-22: i DM scartati qui NON vengono registrati, quindi
        # l'attesa parte sempre dall'ultimo DM elaborato.
        if not limite_dm_appello.puo_elaborare(
            user.id, datetime.now(timezone.utc), DM_APPEAL_PROCESSING_COOLDOWN_SECONDS
        ):
            return

        # SEC-12: UNA query su tutti i server insieme (indice
        # dedicato in moderation_repo), non un giro su ognuno di
        # quelli con cui il bot condivide una guild — con migliaia di
        # server sarebbe una query per ogni singolo DM ricevuto.
        # action_type=BAN_ACTION_TYPE ("spam_trap_ban") esclude già i
        # ban normali (/ban usa action_type="ban"): solo i ban
        # scattati dalla trappola contano come appello qui.
        casi_attivi = await moderation_repo.get_active_cases_for_user_across_guilds(
            user.id, BAN_ACTION_TYPE
        )
        # BUG-24: un server conta una volta sola, col suo caso più
        # recente — due casi attivi nello stesso server non sono "ban
        # su più server".
        candidati: list[tuple[discord.Guild, object]] = []
        for case in latest_case_per_guild(casi_attivi):
            guild = self.bot.get_guild(case.guild_id)
            if guild is not None:
                candidati.append((guild, case))

        if not candidati:
            return  # non è un DM legato a un ban dello Spam Trap: ignorato silenziosamente

        if len(candidati) > 1:
            corrispondenti = [
                gc for gc in candidati if gc[0].name.lower() in (message.content or "").lower()
            ]
            if len(corrispondenti) == 1:
                candidati = corrispondenti
            else:
                nomi = ", ".join(g.name for g, _ in candidati)
                await message.channel.send(
                    f"You have active bans on multiple servers I moderate: {nomi}. "
                    f"Please mention the server name in your message to continue your appeal."
                )
                return

        guild, case = candidati[0]

        last_appeal = await spam_trap_repo.get_last_appeal(guild.id, user.id)
        if not can_appeal(last_appeal):
            await message.channel.send(
                "You can only submit one appeal every 24 hours. Please wait before trying again."
            )
            return

        await spam_trap_repo.set_last_appeal(guild.id, user.id, datetime.now(timezone.utc))

        config = await spam_trap_repo.get_config(guild.id)
        log_channel = guild.get_channel(config.log_channel_id) if config.log_channel_id else None
        if not isinstance(log_channel, discord.TextChannel):
            await message.channel.send(
                "I couldn't reach the staff of that server. Please try again later."
            )
            return

        incident = await spam_trap_repo.get_incident_by_case(guild.id, case.case_number)

        try:
            thread = await log_channel.create_thread(
                name=f"appeal-case-{case.case_number}",
                type=discord.ChannelType.private_thread,
                reason=f"Ban appeal from {user}",
            )
        except discord.HTTPException:
            await message.channel.send(
                "I couldn't open an appeal thread right now. Please try again later."
            )
            return

        appeal_embed = discord.Embed(
            title=f"Ban Appeal — Case #{case.case_number}",
            description=f"**User:** {user.mention} ({user.id})\n\n"
            f"**Appeal message:**\n{message.content or '(no text)'}",
            color=discord.Color.gold(),
        )
        view = AppealActionsView(guild.id, case.case_number, user.id)

        files = []
        if incident is not None and incident.transcript_html:
            transcript_file = discord.File(
                io.BytesIO(incident.transcript_html.encode("utf-8")),
                filename=f"transcript-case-{case.case_number}.html",
            )
            files.append(transcript_file)

        await thread.send(embed=appeal_embed, view=view, files=files)

        await message.channel.send(
            "Your appeal has been submitted to the staff. They will review it "
            "and may respond here."
        )


