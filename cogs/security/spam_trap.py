"""
cogs/security/spam_trap.py
=============================
Spam Trap (SPEC.md §7.3): un canale trappola dove scrivere significa
ban istantaneo. Modulo CANDIDATO PREMIUM.

SEC-8b: prima di tutto il resto, _handle_trigger controlla se chi ha
scritto nella trappola è esente (permesso "Gestisci messaggi" o
"Amministratore", uno dei ruoli staff configurati con
/spamtrap-setup, o un ruolo sopra quello del bot) — in quel caso non
scatta nessun ban né propagazione al global-ban. AppealActionsView
richiede "Bannare i membri" a chi preme i bottoni Unban/Reject/Reply.

Sequenza fissa (vedi PROGRESS.md § Decisioni prese — NON riordinare):
  1. Cattura contenuto del messaggio che ha scatenato la trappola
  2. Raccolta dati per il transcript (PRIMA di qualunque cancellazione)
  3. DM all'utente — PRIMA del ban (dopo, niente server in comune)
  4. Ban con delete_message_seconds (max 7 giorni nativi Discord)
  5. Creazione del case (riusa moderation_cases, action_type
     "spam_trap_ban" — non un proprio sistema di case duplicato)
  6. Purge supplementare (finestra 7-30 giorni, oltre quanto già
     coperto dal ban nativo)
  7. Cleanup webhook/inviti creati dall'utente (via audit log)
  8. Log completo in #spam-log

Nota sul contenuto dei messaggi: NON richiede il Message Content
Intent. Vedi la spiegazione completa in core/spam_trap_logic.py —
il contenuto viene sempre recuperato via fetch REST esplicito
(channel.fetch_message), mai letto dall'evento gateway in tempo
reale. Assunzione sul comportamento reale dell'API Discord, da
verificare sul server di test.

Scope scelto per l'appeal — view NON persistente: a differenza dei
pannelli ticket/vocali (che restano pubblicati per mesi), una
conversazione di appeal è per natura di breve durata. La view ha un
timeout di 7 giorni; se il bot si riavvia nel mezzo di un appeal
aperto, i bottoni di quella specifica conversazione smettono di
rispondere (l'utente può comunque riscrivere in DM per riaprirla,
soggetto al cooldown di 24h). Scelta dichiarata, non un errore.
"""

